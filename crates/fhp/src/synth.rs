//! Derives the bit-sliced collision circuit from the lookup table.
//!
//! The collision is a function of nine bits (six moving, rest, obstacle,
//! chirality) to seven bits. For a variable order, each output (or each
//! output XOR its input, "flip" form) becomes a reduced ordered BDD with
//! nodes shared across outputs, and every node is lowered to at most three
//! gates (AND, AND-NOT, OR, OR-NOT, XOR, NOT), with structural hashing. The
//! generator searches all 9! orders in both forms and keeps the smallest
//! circuit; `fhp gen` writes it as Rust (`collide_gen.rs`) and WGSL
//! (`shaders/collide_gen.wgsl`).

use std::collections::HashMap;

pub const NIN: usize = 9;
pub const NOUT: usize = 7;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Op {
    Input(usize),
    Not(usize),
    And(usize, usize),
    /// a & !b
    AndNot(usize, usize),
    Or(usize, usize),
    /// a | !b
    OrNot(usize, usize),
    Xor(usize, usize),
}

#[derive(Clone, Debug)]
pub struct Circuit {
    pub order: [usize; NIN],
    pub flip: bool,
    pub ops: Vec<Op>,
    pub outputs: [usize; NOUT],
}

impl Circuit {
    /// Gates excluding inputs.
    pub fn gate_count(&self) -> usize {
        self.ops.iter().filter(|o| !matches!(o, Op::Input(_))).count()
    }

    pub fn counts(&self) -> [(&'static str, usize); 6] {
        let mut c = [("and", 0), ("andnot", 0), ("or", 0), ("ornot", 0), ("xor", 0), ("not", 0)];
        for o in &self.ops {
            let k = match o {
                Op::Input(_) => continue,
                Op::And(..) => 0,
                Op::AndNot(..) => 1,
                Op::Or(..) => 2,
                Op::OrNot(..) => 3,
                Op::Xor(..) => 4,
                Op::Not(..) => 5,
            };
            c[k].1 += 1;
        }
        c
    }

    pub fn eval(&self, x: [u64; NIN]) -> [u64; NOUT] {
        let mut v = vec![0u64; self.ops.len()];
        for (i, o) in self.ops.iter().enumerate() {
            v[i] = match *o {
                Op::Input(k) => x[k],
                Op::Not(a) => !v[a],
                Op::And(a, b) => v[a] & v[b],
                Op::AndNot(a, b) => v[a] & !v[b],
                Op::Or(a, b) => v[a] | v[b],
                Op::OrNot(a, b) => v[a] | !v[b],
                Op::Xor(a, b) => v[a] ^ v[b],
            };
        }
        std::array::from_fn(|k| v[self.outputs[k]])
    }

    pub fn to_rust(&self) -> String {
        let mut s = String::new();
        s += "// @generated by `cargo run --release -p fhp -- gen` from rules::table(); do not edit.\n";
        s += &format!("// Variable order {:?}, {} form.\n", self.order, if self.flip { "flip" } else { "direct" });
        s += "//! The FHP-III collision as a bit-sliced circuit (see synth.rs).\n\n";
        s += &format!("/// Gates in `collide` (inputs not counted).\npub const GATES: usize = {};\n\n", self.gate_count());
        s += "/// Inputs: moving bits 0..6, rest, obstacle, chirality. Outputs: moving bits, rest.\n";
        s += "#[inline(always)]\n#[rustfmt::skip]\n";
        s += "pub fn collide<T>(x: [T; 9]) -> [T; 7]\nwhere\n    T: Copy + core::ops::BitAnd<Output = T> + core::ops::BitOr<Output = T> + core::ops::BitXor<Output = T> + core::ops::Not<Output = T>,\n{\n";
        for (i, o) in self.ops.iter().enumerate() {
            let e = match *o {
                Op::Input(k) => format!("x[{k}]"),
                Op::Not(a) => format!("!g{a}"),
                Op::And(a, b) => format!("g{a} & g{b}"),
                Op::AndNot(a, b) => format!("g{a} & !g{b}"),
                Op::Or(a, b) => format!("g{a} | g{b}"),
                Op::OrNot(a, b) => format!("g{a} | !g{b}"),
                Op::Xor(a, b) => format!("g{a} ^ g{b}"),
            };
            s += &format!("    let g{i} = {e};\n");
        }
        let outs: Vec<String> = self.outputs.iter().map(|o| format!("g{o}")).collect();
        s += &format!("    [{}]\n}}\n", outs.join(", "));
        s
    }

    pub fn to_wgsl(&self) -> String {
        let mut s = String::new();
        s += "// @generated by `cargo run --release -p fhp -- gen` from rules::table(); do not edit.\n";
        s += &format!("// FHP-III collision, {} gates. Inputs: moving bits 0..6, rest, obstacle, chirality.\n", self.gate_count());
        s += "fn collide(x0: u32, x1: u32, x2: u32, x3: u32, x4: u32, x5: u32, x6: u32, x7: u32, x8: u32) -> array<u32, 7> {\n";
        for (i, o) in self.ops.iter().enumerate() {
            let e = match *o {
                Op::Input(k) => format!("x{k}"),
                Op::Not(a) => format!("~g{a}"),
                Op::And(a, b) => format!("g{a} & g{b}"),
                Op::AndNot(a, b) => format!("g{a} & ~g{b}"),
                Op::Or(a, b) => format!("g{a} | g{b}"),
                Op::OrNot(a, b) => format!("g{a} | ~g{b}"),
                Op::Xor(a, b) => format!("g{a} ^ g{b}"),
            };
            s += &format!("    let g{i} = {e};\n");
        }
        let outs: Vec<String> = self.outputs.iter().map(|o| format!("g{o}")).collect();
        s += &format!("    return array<u32, 7>({});\n}}\n", outs.join(", "));
        s
    }
}

/// Truth tables of the seven outputs over the 512 inputs
/// (index = state | chirality << 8).
pub fn truth_tables(table: &[[u8; 256]; 2], flip: bool) -> [Vec<bool>; NOUT] {
    std::array::from_fn(|k| {
        (0..512)
            .map(|i| {
                let (s, c) = (i & 255, i >> 8);
                let o = (table[c][s] >> k) & 1 == 1;
                if flip {
                    o ^ ((s >> k) & 1 == 1)
                } else {
                    o
                }
            })
            .collect()
    })
}

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
enum Ref {
    Const(bool),
    Gate(usize),
}

struct Builder {
    ops: Vec<Op>,
    hash: HashMap<Op, usize>,
    inputs: [Option<usize>; NIN],
    /// Sub-function (as packed bits) -> its gate.
    funcs: HashMap<(usize, Vec<u64>), Ref>,
    xors: HashMap<(usize, usize), usize>,
}

fn pack(bits: &[bool]) -> Vec<u64> {
    bits.chunks(64).map(|c| c.iter().enumerate().fold(0u64, |a, (i, &b)| a | ((b as u64) << i))).collect()
}

impl Builder {
    fn op(&mut self, o: Op) -> usize {
        let o = match o {
            Op::And(a, b) if a > b => Op::And(b, a),
            Op::Or(a, b) if a > b => Op::Or(b, a),
            Op::Xor(a, b) if a > b => Op::Xor(b, a),
            o => o,
        };
        if let Some(&g) = self.hash.get(&o) {
            return g;
        }
        self.ops.push(o);
        self.hash.insert(o, self.ops.len() - 1);
        self.ops.len() - 1
    }

    fn input(&mut self, k: usize) -> usize {
        if let Some(g) = self.inputs[k] {
            return g;
        }
        let g = self.op(Op::Input(k));
        self.inputs[k] = Some(g);
        g
    }

    /// `f` is a sub-function over the variables order[level..], index bits
    /// MSB-first in that order.
    fn build(&mut self, f: &[bool], level: usize, order: &[usize; NIN]) -> Ref {
        if f.iter().all(|&b| b) {
            return Ref::Const(true);
        }
        if f.iter().all(|&b| !b) {
            return Ref::Const(false);
        }
        let key = (f.len(), pack(f));
        if let Some(&r) = self.funcs.get(&key) {
            return r;
        }
        let neg: Vec<bool> = f.iter().map(|b| !b).collect();
        let nkey = (f.len(), pack(&neg));
        if let Some(&Ref::Gate(g)) = self.funcs.get(&nkey) {
            let r = Ref::Gate(self.op(Op::Not(g)));
            self.funcs.insert(key, r);
            return r;
        }
        let half = f.len() / 2;
        let (lo_f, hi_f) = (&f[..half], &f[half..]);
        if lo_f == hi_f {
            let r = self.build(lo_f, level + 1, order);
            self.funcs.insert(key, r);
            return r;
        }
        let lo = self.build(lo_f, level + 1, order);
        let hi = self.build(hi_f, level + 1, order);
        let v = self.input(order[level]);
        let complement = lo_f.iter().zip(hi_f).all(|(a, b)| a != b);
        let g = match (lo, hi) {
            (Ref::Const(false), Ref::Const(true)) => v,
            (Ref::Const(true), Ref::Const(false)) => self.op(Op::Not(v)),
            (Ref::Const(false), Ref::Gate(h)) => self.op(Op::And(h, v)),
            (Ref::Gate(l), Ref::Const(false)) => self.op(Op::AndNot(l, v)),
            (Ref::Const(true), Ref::Gate(h)) => self.op(Op::OrNot(h, v)),
            (Ref::Gate(l), Ref::Const(true)) => self.op(Op::Or(l, v)),
            (Ref::Gate(l), Ref::Gate(_)) if complement => self.op(Op::Xor(l, v)),
            (Ref::Gate(l), Ref::Gate(h)) => {
                let x = match self.xors.get(&(l.min(h), l.max(h))) {
                    Some(&x) => x,
                    None => {
                        let x = self.op(Op::Xor(l, h));
                        self.xors.insert((l.min(h), l.max(h)), x);
                        x
                    }
                };
                let a = self.op(Op::And(x, v));
                self.op(Op::Xor(l, a))
            }
            _ => unreachable!(),
        };
        let r = Ref::Gate(g);
        self.funcs.insert(key, r);
        r
    }
}

/// Build the circuit for one variable order.
pub fn synthesize(table: &[[u8; 256]; 2], order: [usize; NIN], flip: bool) -> Circuit {
    let tts = truth_tables(table, flip);
    let mut b = Builder { ops: Vec::new(), hash: HashMap::new(), inputs: [None; NIN], funcs: HashMap::new(), xors: HashMap::new() };
    // Inputs first, in index order, so the generated code reads naturally.
    for k in 0..NIN {
        b.input(k);
    }
    let mut outs = [0usize; NOUT];
    for k in 0..NOUT {
        // Reorder the truth table: new index bit (NIN-1-l) is variable order[l].
        let f: Vec<bool> = (0..512)
            .map(|j| {
                let mut i = 0;
                for (l, &var) in order.iter().enumerate() {
                    if (j >> (NIN - 1 - l)) & 1 == 1 {
                        i |= 1 << var;
                    }
                }
                tts[k][i]
            })
            .collect();
        let r = b.build(&f, 0, &order);
        let g = match r {
            Ref::Gate(g) => g,
            Ref::Const(c) => {
                assert!(flip && !c, "constant output");
                usize::MAX
            }
        };
        outs[k] = if flip {
            let inp = b.input(k);
            if g == usize::MAX {
                inp
            } else {
                b.op(Op::Xor(inp, g))
            }
        } else {
            g
        };
    }
    prune(Circuit { order, flip, ops: b.ops, outputs: outs })
}

/// Drop gates no output depends on (inputs are kept), renumbering.
fn prune(c: Circuit) -> Circuit {
    let mut live = vec![false; c.ops.len()];
    let mut stack: Vec<usize> = c.outputs.to_vec();
    while let Some(g) = stack.pop() {
        if live[g] {
            continue;
        }
        live[g] = true;
        match c.ops[g] {
            Op::Input(_) => {}
            Op::Not(a) => stack.push(a),
            Op::And(a, b) | Op::AndNot(a, b) | Op::Or(a, b) | Op::OrNot(a, b) | Op::Xor(a, b) => {
                stack.push(a);
                stack.push(b)
            }
        }
    }
    let mut map = vec![usize::MAX; c.ops.len()];
    let mut ops = Vec::new();
    for (i, o) in c.ops.iter().enumerate() {
        if !live[i] && !matches!(o, Op::Input(_)) {
            continue;
        }
        let m = |a: usize| map[a];
        let n = match *o {
            Op::Input(k) => Op::Input(k),
            Op::Not(a) => Op::Not(m(a)),
            Op::And(a, b) => Op::And(m(a), m(b)),
            Op::AndNot(a, b) => Op::AndNot(m(a), m(b)),
            Op::Or(a, b) => Op::Or(m(a), m(b)),
            Op::OrNot(a, b) => Op::OrNot(m(a), m(b)),
            Op::Xor(a, b) => Op::Xor(m(a), m(b)),
        };
        map[i] = ops.len();
        ops.push(n);
    }
    let outputs = std::array::from_fn(|k| map[c.outputs[k]]);
    Circuit { order: c.order, flip: c.flip, ops, outputs }
}

/// All permutations of 0..n (Heap's algorithm).
pub fn permutations(n: usize) -> Vec<Vec<usize>> {
    let mut a: Vec<usize> = (0..n).collect();
    let mut out = vec![a.clone()];
    let mut c = vec![0; n];
    let mut i = 0;
    while i < n {
        if c[i] < i {
            if i % 2 == 0 {
                a.swap(0, i);
            } else {
                a.swap(c[i], i);
            }
            out.push(a.clone());
            c[i] += 1;
            i = 0;
        } else {
            c[i] = 0;
            i += 1;
        }
    }
    out
}
