//! The ternary collision (rule `Chiral`) as a bit-sliced circuit, by the
//! method of `crate::synth` (a reduced ordered BDD per output, nodes shared
//! across outputs, each node lowered to at most three gates with structural
//! hashing), generalized to any number of inputs and to don't-cares: the
//! two-bit codes that are not a count (one of the four per channel) never
//! occur, and a node whose cofactors agree wherever both are cared for is
//! merged (the BDD "restrict" heuristic).
//!
//! Inputs: planes 0..14 (channel i is planes 2i and 2i+1), obstacle (14),
//! chirality (15). Outputs: the 14 planes.

use super::{bounce, counts, encode, Table, NCH};
pub use crate::synth::Op;
use std::collections::HashMap;

pub const NIN: usize = 16;
pub const NOUT: usize = 14;
pub const OBST_IN: usize = 14;
pub const CHIR_IN: usize = 15;

/// How a count 0, 1, 2 is stored in a channel's two planes.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Encoding {
    /// (n & 1, n >> 1): 00, 10, 01; 11 never occurs.
    Binary,
    /// (n >= 1, n >= 2): 00, 10, 11; 01 never occurs.
    Thermometer,
}

impl Encoding {
    pub fn bits(self, n: u8) -> (bool, bool) {
        match self {
            Encoding::Binary => (n & 1 == 1, n >> 1 == 1),
            Encoding::Thermometer => (n >= 1, n >= 2),
        }
    }
    pub fn count(self, a: bool, b: bool) -> Option<u8> {
        match (self, a, b) {
            (_, false, false) => Some(0),
            (_, true, false) => Some(1),
            (Encoding::Binary, false, true) => Some(2),
            (Encoding::Thermometer, true, true) => Some(2),
            _ => None,
        }
    }
    /// Planes of a state.
    pub fn planes(self, s: u16) -> u16 {
        let n = counts(s);
        (0..NCH).fold(0u16, |a, i| {
            let (x, y) = self.bits(n[i]);
            a | (x as u16) << (2 * i) | (y as u16) << (2 * i + 1)
        })
    }
    /// State of 14 plane bits, None for a code that is not a count.
    pub fn state(self, p: u16) -> Option<u16> {
        let mut n = [0u8; NCH];
        for i in 0..NCH {
            n[i] = self.count((p >> (2 * i)) & 1 == 1, (p >> (2 * i + 1)) & 1 == 1)?;
        }
        Some(encode(&n))
    }
}

/// Truth table and care set over the 2^16 inputs (index bit k = input k),
/// as 14 output tables.
pub fn truth_tables(t: &Table, enc: Encoding, flip: bool) -> (Vec<Vec<bool>>, Vec<bool>) {
    let n = 1usize << NIN;
    let mut out = vec![vec![false; n]; NOUT];
    let mut care = vec![false; n];
    for i in 0..n {
        let p = (i & 0x3fff) as u16;
        let Some(s) = enc.state(p) else { continue };
        care[i] = true;
        let o = if (i >> OBST_IN) & 1 == 1 { bounce(s) } else { t.chiral[s as usize][(i >> CHIR_IN) & 1] };
        let op = enc.planes(o);
        for k in 0..NOUT {
            let b = (op >> k) & 1 == 1;
            out[k][i] = if flip { b ^ ((p >> k) & 1 == 1) } else { b };
        }
    }
    (out, care)
}

#[derive(Clone, Debug)]
pub struct Circuit {
    pub order: Vec<usize>,
    pub flip: bool,
    pub enc: Encoding,
    pub ops: Vec<Op>,
    pub outputs: Vec<usize>,
}

impl Circuit {
    pub fn gate_count(&self) -> usize {
        self.ops.iter().filter(|o| !matches!(o, Op::Input(_))).count()
    }

    pub fn counts(&self) -> [(&'static str, usize); 6] {
        let mut c = [("and", 0), ("andnot", 0), ("or", 0), ("ornot", 0), ("xor", 0), ("not", 0)];
        for o in &self.ops {
            let k = match o {
                Op::Input(_) => continue,
                Op::And(..) => 0,
                Op::AndNot(..) => 1,
                Op::Or(..) => 2,
                Op::OrNot(..) => 3,
                Op::Xor(..) => 4,
                Op::Not(..) => 5,
            };
            c[k].1 += 1;
        }
        c
    }

    pub fn eval(&self, x: &[u64; NIN]) -> [u64; NOUT] {
        let mut v = vec![0u64; self.ops.len()];
        for (i, o) in self.ops.iter().enumerate() {
            v[i] = match *o {
                Op::Input(k) => x[k],
                Op::Not(a) => !v[a],
                Op::And(a, b) => v[a] & v[b],
                Op::AndNot(a, b) => v[a] & !v[b],
                Op::Or(a, b) => v[a] | v[b],
                Op::OrNot(a, b) => v[a] | !v[b],
                Op::Xor(a, b) => v[a] ^ v[b],
            };
        }
        std::array::from_fn(|k| v[self.outputs[k]])
    }

    fn header(&self) -> String {
        format!(
            "// @generated by `cargo run --release -p fhp --bin ternary -- gen` from ternary::Table (rule Chiral); do not edit.\n// {:?} encoding, variable order {:?}, {} form, {} gates.\n",
            self.enc,
            self.order,
            if self.flip { "flip" } else { "direct" },
            self.gate_count()
        )
    }

    fn expr(o: &Op, inp: impl Fn(usize) -> String, not: &str) -> String {
        match *o {
            Op::Input(k) => inp(k),
            Op::Not(a) => format!("{not}g{a}"),
            Op::And(a, b) => format!("g{a} & g{b}"),
            Op::AndNot(a, b) => format!("g{a} & {not}g{b}"),
            Op::Or(a, b) => format!("g{a} | g{b}"),
            Op::OrNot(a, b) => format!("g{a} | {not}g{b}"),
            Op::Xor(a, b) => format!("g{a} ^ g{b}"),
        }
    }

    pub fn to_rust(&self) -> String {
        let mut s = self.header();
        s += "//! The ternary FHP collision (rule Chiral) as a bit-sliced circuit (see ternary/synth.rs).\n\n";
        s += &format!("/// Gates in `collide` (inputs not counted).\npub const GATES: usize = {};\n", self.gate_count());
        s += &format!("/// Plane encoding of a count.\npub const ENCODING: super::synth::Encoding = super::synth::Encoding::{:?};\n\n", self.enc);
        s += "/// Inputs: planes 0..14, obstacle, chirality. Outputs: planes 0..14.\n";
        s += "#[inline(always)]\n#[rustfmt::skip]\n";
        s += "pub fn collide<T>(x: [T; 16]) -> [T; 14]\nwhere\n    T: Copy + core::ops::BitAnd<Output = T> + core::ops::BitOr<Output = T> + core::ops::BitXor<Output = T> + core::ops::Not<Output = T>,\n{\n";
        for (i, o) in self.ops.iter().enumerate() {
            s += &format!("    let g{i} = {};\n", Self::expr(o, |k| format!("x[{k}]"), "!"));
        }
        let outs: Vec<String> = self.outputs.iter().map(|o| format!("g{o}")).collect();
        s += &format!("    [{}]\n}}\n", outs.join(", "));
        s
    }

    pub fn to_wgsl(&self) -> String {
        let mut s = self.header();
        s += "fn collide(x: array<u32, 16>) -> array<u32, 14> {\n";
        for (i, o) in self.ops.iter().enumerate() {
            s += &format!("    let g{i} = {};\n", Self::expr(o, |k| format!("x[{k}]"), "~"));
        }
        let outs: Vec<String> = self.outputs.iter().map(|o| format!("g{o}")).collect();
        s += &format!("    return array<u32, 14>({});\n}}\n", outs.join(", "));
        s
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
enum Ref {
    Const(bool),
    Gate(usize),
}

fn pack(bits: &[bool]) -> Vec<u64> {
    bits.chunks(64).map(|c| c.iter().enumerate().fold(0u64, |a, (i, &b)| a | ((b as u64) << i))).collect()
}

struct Builder {
    ops: Vec<Op>,
    hash: HashMap<Op, usize>,
    inputs: Vec<Option<usize>>,
    funcs: HashMap<(usize, Vec<u64>, Vec<u64>), Ref>,
    xors: HashMap<(usize, usize), usize>,
}

impl Builder {
    fn op(&mut self, o: Op) -> usize {
        let o = match o {
            Op::And(a, b) if a > b => Op::And(b, a),
            Op::Or(a, b) if a > b => Op::Or(b, a),
            Op::Xor(a, b) if a > b => Op::Xor(b, a),
            o => o,
        };
        if let Some(&g) = self.hash.get(&o) {
            return g;
        }
        self.ops.push(o);
        self.hash.insert(o, self.ops.len() - 1);
        self.ops.len() - 1
    }

    fn input(&mut self, k: usize) -> usize {
        if let Some(g) = self.inputs[k] {
            return g;
        }
        let g = self.op(Op::Input(k));
        self.inputs[k] = Some(g);
        g
    }

    /// `f` and `care` over the variables order[level..], index bits MSB-first in that order.
    fn build(&mut self, f: &[bool], care: &[bool], level: usize, order: &[usize]) -> Ref {
        let (mut any_t, mut any_f, mut any_c) = (false, false, false);
        for (&b, &c) in f.iter().zip(care) {
            if c {
                any_c = true;
                if b {
                    any_t = true;
                } else {
                    any_f = true;
                }
            }
        }
        if !any_c || !any_t {
            return Ref::Const(false);
        }
        if !any_f {
            return Ref::Const(true);
        }
        let fm: Vec<bool> = f.iter().zip(care).map(|(&b, &c)| b && c).collect();
        let key = (f.len(), pack(&fm), pack(care));
        if let Some(&r) = self.funcs.get(&key) {
            return r;
        }
        let neg: Vec<bool> = f.iter().zip(care).map(|(&b, &c)| !b && c).collect();
        let nkey = (f.len(), pack(&neg), key.2.clone());
        if let Some(&Ref::Gate(g)) = self.funcs.get(&nkey) {
            let r = Ref::Gate(self.op(Op::Not(g)));
            self.funcs.insert(key, r);
            return r;
        }
        let half = f.len() / 2;
        let (lo_f, hi_f) = (&f[..half], &f[half..]);
        let (lo_c, hi_c) = (&care[..half], &care[half..]);
        let compatible = (0..half).all(|j| !(lo_c[j] && hi_c[j]) || lo_f[j] == hi_f[j]);
        if compatible {
            let mf: Vec<bool> = (0..half).map(|j| if lo_c[j] { lo_f[j] } else { hi_f[j] }).collect();
            let mc: Vec<bool> = (0..half).map(|j| lo_c[j] || hi_c[j]).collect();
            let r = self.build(&mf, &mc, level + 1, order);
            self.funcs.insert(key, r);
            return r;
        }
        let lo = self.build(lo_f, lo_c, level + 1, order);
        let hi = self.build(hi_f, hi_c, level + 1, order);
        let v = self.input(order[level]);
        let g = match (lo, hi) {
            (Ref::Const(false), Ref::Const(true)) => v,
            (Ref::Const(true), Ref::Const(false)) => self.op(Op::Not(v)),
            (Ref::Const(false), Ref::Gate(h)) => self.op(Op::And(h, v)),
            (Ref::Gate(l), Ref::Const(false)) => self.op(Op::AndNot(l, v)),
            (Ref::Const(true), Ref::Gate(h)) => self.op(Op::OrNot(h, v)),
            (Ref::Gate(l), Ref::Const(true)) => self.op(Op::Or(l, v)),
            (Ref::Gate(l), Ref::Gate(h)) if self.ops[h] == Op::Not(l) || self.ops[l] == Op::Not(h) => self.op(Op::Xor(l, v)),
            (Ref::Gate(l), Ref::Gate(h)) => {
                let k = (l.min(h), l.max(h));
                let x = match self.xors.get(&k) {
                    Some(&x) => x,
                    None => {
                        let x = self.op(Op::Xor(l, h));
                        self.xors.insert(k, x);
                        x
                    }
                };
                let a = self.op(Op::And(x, v));
                self.op(Op::Xor(l, a))
            }
            _ => unreachable!("equal constants are caught above"),
        };
        let r = Ref::Gate(g);
        self.funcs.insert(key, r);
        r
    }
}

/// Build the circuit for one variable order, form and encoding.
pub fn synthesize(tts: &(Vec<Vec<bool>>, Vec<bool>), enc: Encoding, order: &[usize], flip: bool) -> Circuit {
    let (outs_tt, care) = tts;
    let n = 1usize << NIN;
    let mut b = Builder { ops: Vec::new(), hash: HashMap::new(), inputs: vec![None; NIN], funcs: HashMap::new(), xors: HashMap::new() };
    for k in 0..NIN {
        b.input(k);
    }
    // perm[j] = original index of reordered index j.
    let perm: Vec<usize> = (0..n)
        .map(|j| {
            let mut i = 0;
            for (l, &var) in order.iter().enumerate() {
                if (j >> (NIN - 1 - l)) & 1 == 1 {
                    i |= 1 << var;
                }
            }
            i
        })
        .collect();
    let c: Vec<bool> = perm.iter().map(|&i| care[i]).collect();
    let mut outs = vec![0usize; NOUT];
    for k in 0..NOUT {
        let f: Vec<bool> = perm.iter().map(|&i| outs_tt[k][i]).collect();
        let r = b.build(&f, &c, 0, order);
        outs[k] = match (r, flip) {
            (Ref::Gate(g), false) => g,
            (Ref::Gate(g), true) => {
                let inp = b.input(k);
                b.op(Op::Xor(inp, g))
            }
            (Ref::Const(false), true) => b.input(k),
            (Ref::Const(c), _) => panic!("constant output {k} ({c})"),
        };
    }
    prune(Circuit { order: order.to_vec(), flip, enc, ops: b.ops, outputs: outs })
}

fn prune(c: Circuit) -> Circuit {
    let mut live = vec![false; c.ops.len()];
    let mut stack: Vec<usize> = c.outputs.clone();
    while let Some(g) = stack.pop() {
        if live[g] {
            continue;
        }
        live[g] = true;
        match c.ops[g] {
            Op::Input(_) => {}
            Op::Not(a) => stack.push(a),
            Op::And(a, b) | Op::AndNot(a, b) | Op::Or(a, b) | Op::OrNot(a, b) | Op::Xor(a, b) => {
                stack.push(a);
                stack.push(b)
            }
        }
    }
    let mut map = vec![usize::MAX; c.ops.len()];
    let mut ops = Vec::new();
    for (i, o) in c.ops.iter().enumerate() {
        if !live[i] && !matches!(o, Op::Input(_)) {
            continue;
        }
        let m = |a: usize| map[a];
        let n = match *o {
            Op::Input(k) => Op::Input(k),
            Op::Not(a) => Op::Not(m(a)),
            Op::And(a, b) => Op::And(m(a), m(b)),
            Op::AndNot(a, b) => Op::AndNot(m(a), m(b)),
            Op::Or(a, b) => Op::Or(m(a), m(b)),
            Op::OrNot(a, b) => Op::OrNot(m(a), m(b)),
            Op::Xor(a, b) => Op::Xor(m(a), m(b)),
        };
        map[i] = ops.len();
        ops.push(n);
    }
    let outputs = c.outputs.iter().map(|&o| map[o]).collect();
    Circuit { order: c.order, flip: c.flip, enc: c.enc, ops, outputs }
}

/// Check a circuit against the table on every valid input.
pub fn verify(c: &Circuit, t: &Table) -> Result<(), String> {
    let n = 1usize << NIN;
    let mut i = 0;
    while i < n {
        let mut x = [0u64; NIN];
        let lanes = 64.min(n - i);
        let mut valid = 0u64;
        for l in 0..lanes {
            let v = i + l;
            if c.enc.state((v & 0x3fff) as u16).is_some() {
                valid |= 1 << l;
            }
            for k in 0..NIN {
                x[k] |= (((v >> k) & 1) as u64) << l;
            }
        }
        let o = c.eval(&x);
        for l in 0..lanes {
            if (valid >> l) & 1 == 0 {
                continue;
            }
            let v = i + l;
            let s = c.enc.state((v & 0x3fff) as u16).unwrap();
            let want = if (v >> OBST_IN) & 1 == 1 { bounce(s) } else { t.chiral[s as usize][(v >> CHIR_IN) & 1] };
            let wp = c.enc.planes(want);
            for k in 0..NOUT {
                if ((o[k] >> l) & 1) as u16 != (wp >> k) & 1 {
                    return Err(format!("input {v:#06x} output {k}"));
                }
            }
        }
        i += 64;
    }
    Ok(())
}
